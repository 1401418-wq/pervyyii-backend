def _client_ip(request: Request) -> str:
    xr = request.headers.get("x-real-ip", "").strip()
    if xr:
        return xr
    xff = request.headers.get("x-forwarded-for", "")
    if xff:
        return xff.split(",")[0].strip()
    return request.client.host if request.client else "unknown"


def _safe_err(e) -> str:
    """Строка ошибки без секретов (токен бота / креды прокси) — для логов."""
    s = re.sub(r"bot\d+:[A-Za-z0-9_-]+", "bot<redacted>", str(e))
    s = re.sub(r"//[^/@\s]+@", "//<redacted>@", s)
    return s[:300]


def _rate_limited(key: str, limit: int = 10, window: int = 3600) -> bool:
    now = _time.time()
    bucket = [t for t in _rate_buckets.get(key, []) if now - t < window]
    if len(bucket) >= limit:
        _rate_buckets[key] = bucket
        return True
    bucket.append(now)
    _rate_buckets[key] = bucket
    # аварийная чистка, чтобы словарь не рос бесконечно
    if len(_rate_buckets) > 10000:
        for k in [k for k, v in _rate_buckets.items() if not [t for t in v if now - t < window]]:
            _rate_buckets.pop(k, None)
    return False


