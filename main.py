    for task_name in ("_email_retry_task", "_lead_reminder_task", "_lead_notify_task", "_site_lead_retention_task"):
        task = globals().get(task_name)
        if task:
            task.cancel()
            try:
                await task
            except asyncio.CancelledError:
                pass
            globals()[task_name] = None
    if pool:
        await pool.close()


