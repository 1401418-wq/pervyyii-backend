def _clean_html_to_text(html: str, limit: int = 8000) -> dict:
    soup = BeautifulSoup(html, "lxml")
    for tag in soup(["script", "style", "noscript", "iframe", "svg"]):
        tag.decompose()

    title = (soup.title.string or "").strip() if soup.title else ""
    meta_desc = ""
    md = soup.find("meta", attrs={"name": "description"})
    if md and md.get("content"):
        meta_desc = md["content"].strip()

    h1s = [h.get_text(" ", strip=True) for h in soup.find_all("h1")][:5]
    h2s = [h.get_text(" ", strip=True) for h in soup.find_all("h2")][:10]

    has_form = bool(soup.find("form"))
    has_phone = bool(re.search(r"(\+7|8\s?\(?9\d{2}|tel:)", html))
    has_email = bool(re.search(r"[\w.+-]+@[\w-]+\.[\w.-]+", html))
    has_whatsapp = "wa.me" in html or "whatsapp" in html.lower()
    has_telegram = "t.me/" in html or "telegram" in html.lower()
    has_chat_widget = any(s in html.lower() for s in ["jivo", "talk-me", "carrotquest", "verbox", "intercom"])

    body_text = soup.get_text(" ", strip=True)
    body_text = re.sub(r"\s+", " ", body_text)
    if len(body_text) > limit:
        body_text = body_text[:limit] + " […обрезано]"

    return {
        "title": title,
        "meta_desc": meta_desc,
        "h1s": h1s,
        "h2s": h2s,
        "has_form": has_form,
        "has_phone": has_phone,
        "has_email": has_email,
        "has_whatsapp": has_whatsapp,
        "has_telegram": has_telegram,
        "has_chat_widget": has_chat_widget,
        "body_text": body_text,
    }


def _normalize_url(raw: str) -> str:
    raw = (raw or "").strip()
    if not raw:
        return ""
    if not re.match(r"^https?://", raw, re.I):
        raw = "https://" + raw
    p = urlparse(raw)
    if not p.netloc or "." not in p.netloc:
        return ""
    return raw


def _ip_is_public(ip_str: str) -> bool:
    try:
        ip = ipaddress.ip_address(ip_str)
    except ValueError:
        return False
    return not (
        ip.is_private or ip.is_loopback or ip.is_link_local
        or ip.is_reserved or ip.is_multicast or ip.is_unspecified
    )


async def _resolve_ips(host: str) -> list[str]:
    try:
        loop = asyncio.get_event_loop()
        infos = await loop.getaddrinfo(host, None, type=socket.SOCK_STREAM)
    except Exception:
        return []
    seen: list[str] = []
    for i in infos:
        ip = i[4][0]
        if ip not in seen:
            seen.append(ip)
    return seen


async def _host_is_public(host: str) -> bool:
    """Резолвит хост и требует, чтобы ВСЕ адреса были публичными. Быстрый отсев/UX;
    реальная защита от rebinding — в _safe_fetch (пиннинг на IP)."""
    ips = await _resolve_ips(host)
    return bool(ips) and all(_ip_is_public(ip) for ip in ips)


async def _safe_fetch(url: str, verify: bool, headers: dict, max_redirects: int = 5):
    """GET с пиннингом на резолвнутый публичный IP — устойчиво к DNS-rebinding.
    Резолвим хост один раз, проверяем ВСЕ адреса, коннектимся к IP-литералу
    (второго резолва у httpcore нет → окно rebinding закрыто), Host и SNI
    сохраняем для корректной проверки TLS-сертификата по имени."""
    current = url
    for _ in range(max_redirects + 1):
        p = urlparse(current)
        if p.scheme not in ("http", "https") or not p.hostname:
            return None
        if p.port and p.port not in (80, 443):
            return None
        ips = await _resolve_ips(p.hostname)
        if not ips or not all(_ip_is_public(ip) for ip in ips):
            return None
        ip = ips[0]
        port = p.port or (443 if p.scheme == "https" else 80)
        ip_netloc = f"[{ip}]" if ":" in ip else ip
        ip_url = urlunparse((p.scheme, f"{ip_netloc}:{port}", p.path or "/", p.params, p.query, ""))
        req_headers = dict(headers)
        req_headers["Host"] = p.hostname
        exts = {"sni_hostname": p.hostname} if p.scheme == "https" else {}
        async with httpx.AsyncClient(timeout=20, follow_redirects=False, verify=verify) as client:
            req = httpx.Request("GET", ip_url, headers=req_headers, extensions=exts)
            resp = await client.send(req)
        if resp.status_code in (301, 302, 303, 307, 308) and resp.headers.get("location"):
            current = str(httpx.URL(current).join(resp.headers["location"]))
            continue
        return resp
    return None


