def _brief_clean_work(payload: dict, questions: list) -> tuple[dict, list]:
    """Whitelist рабочего брифа: только ключи вопросов этой строки, только строки, с лимитом.

    Возвращает (сохранить, удалить): явно присланная пустая строка — это стирание ранее
    сохранённого ответа, и оно обязано доехать до БД. Иначе клиент видит вопрос пропущенным,
    а стёртый текст продолжает жить в answers и уходить в карточку и админ-вид."""
    allowed = {q["key"] for q in questions}
    out: dict = {}
    deleted: list = []
    for key in allowed:
        val = payload.get(key)
        if not isinstance(val, str):
            continue
        if val.strip():
            out[key] = val.strip()[:BRIEF_WORK_TEXT_LIMIT]
        else:
            deleted.append(key)
    return out, deleted


def _brief_clean(payload: dict) -> dict:
    """Оставляет только известные ключи и значения, режет длину. Незнакомое молча выбрасывает."""
    out: dict = {}
    for key, limit in BRIEF_STR_KEYS.items():
        val = payload.get(key)
        if isinstance(val, str) and val.strip():
            out[key] = val.strip()[:limit]
    for key, max_items in BRIEF_LIST_KEYS.items():
        val = payload.get(key)
        if isinstance(val, list):
            valid = BRIEF_VALID[key]
            items: list = []
            for x in val:
                if isinstance(x, str) and x in valid and x not in items:
                    items.append(x)
            items = items[:max_items]
            # «Пока ниоткуда» взаимоисключающе с остальными каналами.
            if key == "channels" and "none" in items:
                items = ["none"]
            if items:
                out[key] = items
    for key in BRIEF_CHOICE_KEYS:
        val = payload.get(key)
        if isinstance(val, str) and val in BRIEF_VALID[key]:
            out[key] = val
    # Главная задача обязана быть одной из выбранных.
    if out.get("main_task") and out.get("tasks") and out["main_task"] not in out["tasks"]:
        out.pop("main_task")
    # На почту не звонят: межполевая нормализация вместо семантически странных сочетаний.
    if out.get("contact_channel") == "email":
        out["contact_how"] = "write"
    return out


