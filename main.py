# ─────────────────── Обезличивание ПД перед отправкой за рубеж (152-ФЗ) ───────────────────
# За границу (Anthropic/OpenAI) уходит только текст с плейсхолдерами вместо ПД.
# Реальные значения остаются на сервере, ответ обратно un-mask'ается для пользователя.
_EMAIL_RE = re.compile(r"[\w.+-]+@[\w-]+\.[\w.-]+")
_TG_RE = re.compile(r"@[A-Za-z][A-Za-z0-9_]{3,}")
_PHONE_RE = re.compile(r"\+?[78]?[\s\-().]*\d(?:[\s\-().]*\d){9,10}")
_NAME_RE = re.compile(r"(меня зовут|мо[её] имя|зовут меня)\s+([А-ЯЁ][а-яё]+)", re.I)
# Документы/реквизиты (цифровые — ловятся надёжно; типовые размеры/цены ≤7-8 цифр не задеваются)
_PASSPORT_RE = re.compile(r"(?<!\d)\d{4}\s\d{6}(?!\d)")                 # паспорт: серия+номер
_CARDACCT_RE = re.compile(r"(?<!\d)\d{4}(?:[ \-]\d{4}){2,4}(?!\d)")     # карта/счёт группами по 4
_DOCNUM_RE = re.compile(r"(?<!\d)\d{10,20}(?!\d)")                      # ИНН/счёт/карта слитно
# Адрес: требуем номер дома, чтобы не рвать обычный текст («на улице тепло» не сматчится)
_ADDR_RE = re.compile(
    r"(?:ул\.?|улиц\w+|проспект\w*|пр-т|переул\w*|пер\.|шоссе|бульвар\w*|наб\.|набережн\w+|мкр\.?|микрорайон)"
    r"[\s,]+[A-Za-zА-ЯЁа-яё0-9\-. ]{2,30}?,?\s*(?:д\.?\s*)?\d+[а-яА-Я]?",
    re.I,
)


def _mask_pii(text: str, mapping: dict) -> str:
    if not isinstance(text, str):
        return text

    def _ph(kind: str, val: str) -> str:
        for ph, v in mapping.items():
            if v == val:
                return ph
        ph = f"[{kind}_{len(mapping) + 1}]"
        mapping[ph] = val
        return ph

    text = _EMAIL_RE.sub(lambda m: _ph("EMAIL", m.group(0)), text)
    text = _TG_RE.sub(lambda m: _ph("TG", m.group(0)), text)
    text = _ADDR_RE.sub(lambda m: _ph("ADDR", m.group(0)), text)
    text = _PASSPORT_RE.sub(lambda m: _ph("DOC", m.group(0)), text)
    text = _CARDACCT_RE.sub(lambda m: _ph("DOC", m.group(0)), text)
    # Документы-слитно ДО телефона: иначе телефонный regex откусывает часть длинного числа и остаток утекает
    text = _DOCNUM_RE.sub(lambda m: _ph("DOC", m.group(0)), text)
    text = _PHONE_RE.sub(lambda m: _ph("PHONE", m.group(0)), text)
    text = _NAME_RE.sub(lambda m: m.group(1) + " " + _ph("NAME", m.group(2)), text)
    return text


def _unmask(text: str, mapping: dict) -> str:
    for ph, val in mapping.items():
        text = text.replace(ph, val)
    return text


def _mask_messages(messages: list) -> tuple[list, dict]:
    """(обезличенные messages, mapping) — для зарубежного LLM."""
    mapping: dict = {}
    masked = [
        {"role": m["role"], "content": _mask_pii(str(m.get("content", "")), mapping)}
        for m in messages
    ]
    return masked, mapping


def _extract_contact_local(text: str) -> dict:
    """Извлекает контакт из текста ЛОКАЛЬНО (без LLM) — чтобы ПД не уходили за рубеж."""
    phone = _PHONE_RE.search(text)
    tg = _TG_RE.search(text)
    email = _EMAIL_RE.search(text)
    name_m = _NAME_RE.search(text)
    if phone:
        contact = phone.group(0).strip()
    elif tg:
        contact = tg.group(0).strip()
    elif email:
        contact = email.group(0).strip()
    else:
        contact = None
    name = name_m.group(2) if name_m else None
    return {"name": name, "contact": contact, "has_lead": bool(contact)}


def _validate_chat_messages(messages) -> str | None:
    """Возвращает текст ошибки, если тело не проходит лимиты, иначе None."""
    if not isinstance(messages, list) or not messages:
        return "messages is empty"
    if len(messages) > MAX_MESSAGES:
        return "too many messages"
    total = 0
    for m in messages:
        if not isinstance(m, dict) or m.get("role") not in ("user", "assistant"):
            return "invalid message role"
        content = m.get("content")
        if not isinstance(content, str):
            return "message content must be a string"
        if len(content) > MAX_MSG_CHARS:
            return "message too long"
        total += len(content)
    if total > MAX_TOTAL_CHARS:
        return "conversation too long"
    return None


def _normalize_history(msgs: list) -> list:
    """Чередование ролей и старт с user — требование Anthropic. Ведущие assistant
    отбрасываем, соседние одинаковые роли склеиваем."""
    out: list = []
    for m in msgs:
        role = m.get("role")
        if role not in ("user", "assistant"):
            continue
        if not out and role != "user":
            continue
        if out and out[-1]["role"] == role:
            out[-1]["content"] = f"{out[-1]['content']}\n\n{m.get('content', '')}"
        else:
            out.append({"role": role, "content": m.get("content", "")})
    return out

