# Соответствие диаметра купола цирка → диапазон числа мест (данные ПРАЙМ-ТЕНТ). Места зависят
# от диаметра купола и компоновки проходов; НЕ зависят от высоты купола и наклона трибун.
_CIRCUS_SEATS = [
    (24, 550, 600), (25, 600, 650), (28, 700, 800), (30, 800, 950),
    (32, 1000, 1100), (34, 1100, 1150), (36, 1150, 1250), (38, 1300, 1500),
    (42, 1800, 1900), (44, 2000, 2100), (46, 2100, 2200), (48, 2500, 2500),
]


def _circus_seats_for_diameter(d):
    tbl = _CIRCUS_SEATS
    if d <= tbl[0][0]:
        return tbl[0][1], tbl[0][2]
    if d >= tbl[-1][0]:
        return tbl[-1][1], tbl[-1][2]
    for i in range(len(tbl) - 1):
        d0, l0, h0 = tbl[i]
        d1, l1, h1 = tbl[i + 1]
        if d0 <= d <= d1:
            t = (d - d0) / (d1 - d0) if d1 != d0 else 0
            return int(round(l0 + t * (l1 - l0))), int(round(h0 + t * (h1 - h0)))
    return tbl[-1][1], tbl[-1][2]


def _circus_diameter_for_seats(n):
    for d, l, h in _CIRCUS_SEATS:
        if h >= n:
            return d
    return _CIRCUS_SEATS[-1][0]


def pt_calculate_price(construction=None, width=None, length=None, wall_height=None,
                       area=None, with_walls=False, shade_area=None,
                       dome_diameter=None, seats=None, **_):
    def _num(x, lo, hi):
        """Конечное положительное число в [lo, hi]; иначе None (режет отрицательные, NaN, Inf, гигантские)."""
        try:
            v = float(x)
        except (TypeError, ValueError):
            return None
        return v if (math.isfinite(v) and lo <= v <= hi) else None

    width = _num(width, 1, 500)
    length = _num(length, 1, 500)
    wall_height = _num(wall_height, 1, 50)
    area = _num(area, 1, 250000)
    shade_area = _num(shade_area, 1, 100000)
    dome_diameter = _num(dome_diameter, 1, 100)
    _seats = _num(seats, 1, 100000)
    seats = int(_seats) if (_seats is not None and _seats.is_integer()) else None

    def _area():
        if area:
            return area
        if width and length:
            return width * length
        return None

    def _perim():
        if width and length:
            return 2.0 * (width + length)
        return None

    c = construction
    if c in ("angar_cold", "angar_warm"):
        a, pm = _area(), _perim()
        if not (a and pm and wall_height):
            return {"ok": False, "need": "положительные ширина, длина и высота стен ангара"}
        base = a * 8000 + 90000 + pm * wall_height * 1500
        if c == "angar_warm":
            base *= 1.35
        total = base * 1.40
        kind = "утеплённого" if c == "angar_warm" else "холодного"
        return {"ok": True, "text": f"Ориентир {kind} ангара: порядка {_rub(total)} рублей С МОНТАЖОМ (за само сооружение с монтажом). {_PT_SEP_ANGAR}"}

    if c == "shater_restaurant":
        a, pm = _area(), _perim()
        if not a:
            return {"ok": False, "need": "положительные ширина и длина (или площадь) шатра/павильона"}
        lo, hi = a * 11000 + 90000, a * 13000 + 90000
        if with_walls:
            if not (pm and wall_height):
                return {"ok": False, "need": "положительная высота стен (для варианта со стенами)"}
            w = pm * wall_height * 1500
            lo += w
            hi += w
        return {"ok": True, "text": f"Ориентир шатра/павильона: порядка {_rub_range(lo, hi)} рублей за само сооружение. {_PT_SEP_SHATER}"}

    if c == "vozduhoopornoe":
        a = _area()
        if not a:
            return {"ok": False, "need": "положительная площадь (или ширина и длина)"}
        return {"ok": True, "text": f"Ориентир воздухоопорного сооружения: порядка {_rub(a * 8000)} рублей. {_PT_SEP_VOZDUH}"}

    if c == "gipar":
        s = shade_area or _area()
        if not s:
            return {"ok": False, "need": "положительная площадь зоны тени"}
        return {"ok": True, "text": f"Ориентир теневого паруса-гипара: порядка {_rub_range(s * 7500, s * 10000)} рублей за само сооружение. Стен у гипаров не бывает. {_PT_SEP_GIPAR}"}

    if c == "circus":
        max_seats = _CIRCUS_SEATS[-1][2]
        d = dome_diameter
        if d is not None and not (24 <= d <= 48):
            return {"ok": False, "need": "стандартные купола ПРАЙМ-ТЕНТ — диаметром 24–48 м; для другого диаметра нужен расчёт менеджера"}
        if seats and not d:
            if seats > max_seats:
                return {"ok": False, "need": f"наши модели купола (24–48 м) вмещают примерно до {max_seats} мест; для большего — расчёт менеджера"}
            d = _circus_diameter_for_seats(seats)
        parts = []
        if d:
            parts.append(f"купол Ø{int(round(d))} м с опорными конструкциями — порядка {_rub((d * d * 3.14 / 4) * 16500)} рублей")
        if seats:
            if d:
                _, sh = _circus_seats_for_diameter(d)
                if seats > sh:
                    return {"ok": False, "need": f"купол Ø{int(round(d))} м вмещает примерно до {sh} мест — для {seats} мест нужен купол большего диаметра; уточни диаметр купола или число мест"}
            parts.append(f"трибуны на {seats} мест — порядка {_rub(seats * 6500)} рублей")
        elif d:
            sl, sh = _circus_seats_for_diameter(d)
            seats_str = f"{sl}" if sl == sh else f"{sl}–{sh}"
            parts.append(f"трибуны примерно на {seats_str} мест — порядка {_rub_range(sl * 6500, sh * 6500)} рублей")
        if not parts:
            return {"ok": False, "need": "диаметр купола или желаемая вместимость зала"}
        return {"ok": True, "text": "Ориентир по цирку (называй суммы РАЗДЕЛЬНО, ставки и расчёт НЕ раскрывай): " + "; ".join(parts) + ". Барьер манежа, писта, полы, доп. шатры и прочая комплектация — отдельно. Итоговая стоимость зависит от комплектации, материалов, опорных конструкций и монтажа; точный расчёт делает менеджер."}

    return {"ok": False, "need": "тип конструкции"}


