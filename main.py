def _sanitize_referrer(ref: str) -> str:
    """Метка источника: только https?://host/path — без query/fragment/userinfo, с лимитом длины."""
    if not ref:
        return ""
    m = re.match(r"^https?://(?:[^/@?#\s]*@)?([^/:?#\s]+)(?::\d+)?(/[^?#\s]*)?", ref.strip())
    if not m:
        return ""
    return (m.group(1) + (m.group(2) or "/"))[:200]


